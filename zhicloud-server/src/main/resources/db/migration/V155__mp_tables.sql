-- V155: 微信公众号(mp)模块 8 张 mp_* 表
-- 来源: zhicloud-module-mp dal/dataobject 各 DO 字段逐表生成（模块无现成 DDL、仓库与上游均无建表脚本）。
-- 类型口径: String->varchar、Long->bigint、Integer->int、Boolean->bit(1)、Double->double、LocalDateTime->datetime、List<..>->json。
