-- 幂等: CREATE TABLE IF NOT EXISTS。

CREATE TABLE IF NOT EXISTS `mp_account` (
    `id` bigint NOT NULL AUTO_INCREMENT COMMENT '编号',
    `name` varchar(64) NOT NULL COMMENT '公众号名称',
    `account` varchar(64) NOT NULL COMMENT '公众号账号',
    `app_id` varchar(64) NOT NULL COMMENT '公众号 appid',
    `app_secret` varchar(64) NOT NULL COMMENT '公众号密钥',
    `token` varchar(64) NOT NULL COMMENT '公众号令牌',
    `aes_key` varchar(64) DEFAULT NULL COMMENT '消息加解密密钥',
    `qr_code_url` varchar(255) DEFAULT NULL COMMENT '二维码图片 URL',
    `remark` varchar(255) DEFAULT NULL COMMENT '备注',
    `creator` varchar(64) DEFAULT '' COMMENT '创建者',
    `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updater` varchar(64) DEFAULT '' COMMENT '更新者',
    `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` bit(1) NOT NULL DEFAULT b'0' COMMENT '是否删除',
    `tenant_id` bigint NOT NULL DEFAULT 0 COMMENT '租户编号',
    PRIMARY KEY (`id`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci COMMENT = '公众号 mp_account 表';

