-- ============================================================
-- V112: QMS document control, audit and instrument tables
-- Source reviewed from sql/mysql/qms_document_audit.sql and sql/mysql/qms_instrument.sql.
-- The source scripts were not part of the Flyway migration chain.
-- No mock/business rows are inserted by this migration.
-- All ids use AUTO_INCREMENT because MyBatis-Plus IdType=AUTO is configured.
-- Business unique keys are tenant-scoped to prevent cross-tenant collisions.
-- ============================================================

CREATE TABLE IF NOT EXISTS `qms_document` (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    doc_no VARCHAR(64) NOT NULL COMMENT '文件编号',
    title VARCHAR(255) NOT NULL COMMENT '标题',
    doc_type TINYINT NOT NULL COMMENT '文件类型（10 质量手册 20 程序文件 30 作业指导书 40 质量记录 50 外来文件）',
    version VARCHAR(32) NOT NULL DEFAULT '1.0' COMMENT '版本号',
    status TINYINT NOT NULL DEFAULT 10 COMMENT '状态（10 草稿 20 待审 30 已发布 40 已作废 50 已回收）',
    effective_date DATE COMMENT '生效日期',
    expiry_date DATE COMMENT '失效日期',
    approver_id BIGINT COMMENT '审批人 ID',
    approve_date DATETIME COMMENT '审批日期',
    owner_dept_id BIGINT COMMENT '归属部门 ID',
    file_url VARCHAR(500) COMMENT '文件 URL',
    remark VARCHAR(500) COMMENT '备注',
    sort INT DEFAULT 0 COMMENT '排序',
    creator VARCHAR(64) COMMENT '创建者',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updater VARCHAR(64) COMMENT '更新者',
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    deleted BIT(1) DEFAULT 0 COMMENT '是否删除',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_tenant_doc_no` (`tenant_id`, `doc_no`),
    KEY `idx_tenant_doc_type` (`tenant_id`, `doc_type`),
    KEY `idx_tenant_status` (`tenant_id`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='QMS 受控文档主表';

